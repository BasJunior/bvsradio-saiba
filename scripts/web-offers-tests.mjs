assert.match(studioArtworkPage, /track, release, beat, or beat pack/, 'Studio artwork page must explain release and beat coverage')
assert.match(studioArtworkClient, /scope="releases"/, 'Studio artwork tool must keep track/release artwork changes')
assert.match(studioArtworkClient, /scope="beats"/, 'Studio artwork tool must expose beat/beat-pack artwork changes')
assert.match(studioArtworkClient, /Change beat or beat pack cover artwork/, 'producer artwork form must be clearly labelled')
assert.match(artworkForm, /New cover image/, 'artwork form must expose a new cover upload')
