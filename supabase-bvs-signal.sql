-- BVS Signal: make editorial selection and listener discovery visible.
-- Apply after supabase-final-sprint-core.sql (track_play_events must exist).

create table if not exists public.track_signal_config (
  track_id uuid primary key references public.tracks(id) on delete cascade,
  first_spin_scheduled_at timestamptz,
  editorial_reason text,
  breakout_at timestamptz,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint track_signal_editorial_reason_length check (
    editorial_reason is null or char_length(editorial_reason) <= 500
  )
);

create table if not exists public.track_catches (
  id bigint generated by default as identity primary key,
  track_id uuid not null references public.tracks(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  source text not null default 'unknown',
  created_at timestamptz not null default now(),
  constraint track_catches_source_check check (
    source in ('station', 'song', 'share', 'explore', 'unknown')
  ),
  unique (track_id, user_id)
);

create index if not exists idx_track_catches_track_created
  on public.track_catches(track_id, created_at asc);

create index if not exists idx_track_catches_user_created
  on public.track_catches(user_id, created_at desc);

-- First Spin is media truth, not a clock transition. The scheduled time lives in
-- track_signal_config; the played time is derived only from a recorded station play.
create or replace view public.track_first_station_spin as
select track_id, min(created_at) as first_spin_played_at
from public.track_play_events
where source = 'station'
group by track_id;

alter table public.track_signal_config enable row level security;
alter table public.track_catches enable row level security;

-- Intentionally no direct client policies in v1. Signal reads/writes go through
-- BVS server routes so only public approved tracks expose listener Signal and
-- clients cannot forge another member's discovery timestamp.
revoke all on table public.track_signal_config from anon, authenticated;
revoke all on table public.track_catches from anon, authenticated;
revoke all on table public.track_first_station_spin from anon, authenticated;
grant all on table public.track_signal_config to service_role;
grant all on table public.track_catches to service_role;
grant select on table public.track_first_station_spin to service_role;

comment on table public.track_signal_config is
  'Editorial Signal metadata for a public BVS track: scheduled first spin, selection note and breakout state.';

comment on table public.track_catches is
  'One Catch per listener per track, preserving when the listener marked the BVS discovery.';

comment on view public.track_first_station_spin is
  'Actual First Spin proof derived from the earliest track_play_events row whose source is station.';
